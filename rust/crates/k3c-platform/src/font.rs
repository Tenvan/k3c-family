//! 5×7-Pixel-Schrift: Großbuchstaben, Ziffern, Satzzeichen. Kleinbuchstaben und Umlaute
//! werden auf Großbuchstaben abgebildet, Unbekanntes als Kästchen gezeichnet.

pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;
/// Zeichenabstand in Pixeln der Schrift (Breite + 1 Lücke).
pub const ADVANCE: usize = GLYPH_W + 1;

type G = [&'static str; GLYPH_H];

const BOX: G = ["11111", "10001", "10001", "10001", "10001", "10001", "11111"];
const BLANK: G = ["00000"; GLYPH_H];

fn fold(c: char) -> char {
    match c {
        'ä' | 'Ä' => 'A',
        'ö' | 'Ö' => 'O',
        'ü' | 'Ü' => 'U',
        'ß' => 'S',
        c => c.to_ascii_uppercase(),
    }
}

