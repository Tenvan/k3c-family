/// Bitmuster eines Zeichens, Zeilen von oben, `'1'` = gesetzt.
pub fn glyph(c: char) -> G {
    let c = fold(c);
    letter(c).or_else(|| digit(c)).or_else(|| symbol(c)).unwrap_or(BOX)
}

/// Ruft `f(x, y, länge)` je zusammenhängendem Pixelstreifen einer Zeile auf (Pixel der Schrift).
pub fn runs(c: char, mut f: impl FnMut(usize, usize, usize)) {
    for (y, row) in glyph(c).iter().enumerate() {
        let b = row.as_bytes();
        let mut x = 0;
        while x < b.len() {
            if b[x] == b'1' {
                let start = x;
                while x < b.len() && b[x] == b'1' {
                    x += 1;
                }
                f(start, y, x - start);
            } else {
                x += 1;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn jedes_glyph_hat_sieben_zeilen_zu_fuenf_spalten() {
        for c in (' '..='~').chain(['ä', 'ö', 'ü', 'ß', '€']) {
            for row in glyph(c) {
                assert_eq!(row.len(), GLYPH_W, "{c:?}");
            }
        }
    }

    #[test]
    fn streifen_fassen_zusammenhaengende_pixel() {
        let mut v = Vec::new();
        runs('T', |x, y, n| v.push((x, y, n)));
        assert_eq!(v[0], (0, 0, 5));
        assert_eq!(v[1], (2, 1, 1));
    }

    #[test]
    fn klein_und_umlaut_werden_gross() {
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('ö'), glyph('O'));
        assert_eq!(glyph('€'), BOX);
    }
}
