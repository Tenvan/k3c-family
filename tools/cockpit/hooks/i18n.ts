export const STRINGS: { readonly de: Record<Key, string>; readonly en: Record<Key, string> } = { de, en }

// Text in der gewählten Sprache; `{name}` wird aus `vars` ersetzt, unbekannte Platzhalter bleiben stehen.
export function t(lang: UiLang, key: Key, vars?: Record<string, string | number>): string {
  const text = STRINGS[lang][key]
  return vars === undefined ? text : text.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
}
